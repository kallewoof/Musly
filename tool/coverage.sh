#!/bin/sh
# coverage.sh - line coverage of lib/ under the unit tests, held to the floor in coverage_floor.txt.
#
# Usage: tool/coverage.sh            measure; fail if below the floor
#        tool/coverage.sh --update   measure; write the result (one decimal, rounded down) as the floor
#
# - Every library file is imported by a throwaway generated test, so a file no test loads counts as 0%
#   instead of dropping out of the total.
# - The generated translations (lib/l10n/) are excluded: 90k lines of tables would swamp the number.
# - test/integration/ is left out: it runs only where a live server is configured, so with it the
#   number would depend on the machine. The pre-commit hook runs it separately.

set -eu
cd "$(dirname "$0")/.."

floor_file=coverage_floor.txt
all_files=test/_coverage_all_files_test.dart
log="$(mktemp -t musly-coverage.XXXXXX)"
trap 'rm -f "$all_files"' EXIT

{
  echo "// Generated by tool/coverage.sh and deleted after the run."
  echo "// ignore_for_file: unused_import"
  find lib -name '*.dart' -not -path 'lib/l10n/*' | sort | sed "s|^lib/\(.*\)|import 'package:musly/\1';|"
  echo "import 'package:flutter_test/flutter_test.dart';"
  echo "void main() => test('every library file loads', () {});"
} >"$all_files"

targets="$(find test -mindepth 1 -maxdepth 1 \( -type d -o -name '*_test.dart' \) -not -name integration | sort)"

# Persisted, then summarised: a filtered stream can hide the line that says what failed.
echo "coverage: flutter test --coverage (log: $log)"
# shellcheck disable=SC2086 # $targets is a list of paths without spaces
if ! flutter test --coverage --reporter expanded $targets >"$log" 2>&1; then
  sed -n '/^Failing tests:/,$p' "$log"
  echo "coverage FAILED: tests failed; the full output is in $log"
  exit 1
fi
grep -E '^[0-9]+:[0-9]+ \+[0-9]+' "$log" | tail -1
rm -f "$log"

measured="$(awk -F: '
  /^SF:/ { skip = ($2 ~ /^lib\/l10n\//) }
  /^LF:/ { if (!skip) found += $2 }
  /^LH:/ { if (!skip) hit += $2 }
  END { if (found == 0) exit 1; printf "%.2f", 100 * hit / found }' coverage/lcov.info)"

if [ "${1:-}" = "--update" ]; then
  awk -v m="$measured" 'BEGIN { printf "%.1f\n", int(m * 10) / 10 }' >"$floor_file"
  echo "coverage: $measured%; floor set to $(cat "$floor_file")%"
  exit 0
fi

floor="$(cat "$floor_file")"
if awk -v m="$measured" -v f="$floor" 'BEGIN { exit !(m < f) }'; then
  echo "coverage FAILED: $measured% is below the floor of $floor% ($floor_file)"
  exit 1
fi
echo "coverage: $measured% (floor $floor%)"
if awk -v m="$measured" -v f="$floor" 'BEGIN { exit !(m >= f + 0.5) }'; then
  echo "coverage: $measured% clears the floor by 0.5 points or more; raise it: tool/coverage.sh --update"
fi
